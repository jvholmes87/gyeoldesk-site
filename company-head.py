#!/usr/bin/env python3
"""Rewrite a company copy's index.html head, no-JS text and web manifest from companies/<slug>.json.
Usage: company-head.py companies/gnc.json <company repo dir>
Company desks are private workspaces: noindex, but link previews (KakaoTalk, Slack, email) show the company."""
import html, json, re, sys
cfg = json.load(open(sys.argv[1], encoding='utf-8')); dest = sys.argv[2]
e = lambda s: html.escape(s, quote=True)
url = f"https://{cfg['slug']}.gyeoldesk.com/"; a = cfg['assets']
head = f'''  <!-- head:start (generated by company-head.py from companies/{cfg['slug']}.json) -->
  <title>{e(cfg['title'])}</title>
  <meta name="application-name" content="{e(cfg['title'])}">
  <meta name="description" content="{e(cfg['description'])}">
  <meta name="robots" content="noindex, nofollow">
  <meta name="google" content="notranslate">
  <meta name="theme-color" content="{e(cfg['theme'])}">
  <link rel="icon" href="{a}/icon-32.png" type="image/png" sizes="32x32">
  <link rel="icon" href="{a}/icon-192.png" type="image/png" sizes="192x192">
  <link rel="apple-touch-icon" href="{a}/icon-180.png">
  <link rel="manifest" href="site.webmanifest">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="{e(cfg['title'])}">
  <meta property="og:title" content="{e(cfg['title'])}">
  <meta property="og:description" content="{e(cfg['description'])} {e(cfg['description_ko'])}">
  <meta property="og:url" content="{url}">
  <meta property="og:image" content="{url}{a}/og-image.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:locale" content="en_US">
  <meta property="og:locale:alternate" content="ko_KR">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="{e(cfg['title'])}">
  <meta name="twitter:description" content="{e(cfg['description'])}">
  <meta name="twitter:image" content="{url}{a}/og-image.png">
  <!-- head:end -->'''
seo = f'''    <!-- seo:start -->
    <main class="seo">
      <h1>{e(cfg['title'])}</h1>
      <p>{e(cfg['description'])}</p>
      <p lang="ko">{e(cfg['description_ko'])}</p>
      <p>Powered by <a href="https://gyeoldesk.com/">Gyeoldesk 결데스크</a>.</p>
    </main>
    <!-- seo:end -->'''
p = f'{dest}/index.html'; s = open(p, encoding='utf-8').read()
s, n1 = re.subn(r'  <!-- head:start.*?<!-- head:end -->', lambda m: head, s, flags=re.S)
s, n2 = re.subn(r'    <!-- seo:start -->.*?<!-- seo:end -->', lambda m: seo, s, flags=re.S)
assert n1 == 1 and n2 == 1, 'markers missing in index.html'
open(p, 'w', encoding='utf-8').write(s)
man = {"name": cfg['title'], "short_name": cfg['short'], "description": cfg['description'], "lang": "en",
       "start_url": "/", "scope": "/", "display": "standalone", "background_color": "#FFFFFF", "theme_color": cfg['theme'],
       "icons": [{"src": f"{a}/icon-192.png", "sizes": "192x192", "type": "image/png"},
                 {"src": f"{a}/icon-512.png", "sizes": "512x512", "type": "image/png"},
                 {"src": f"{a}/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
json.dump(man, open(f'{dest}/site.webmanifest', 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
print('company head:', cfg['title'])
